buildMetaUrl.searchParams.set('v', new URL(self.location.href).searchParams.get('v') || '');
importScripts(buildMetaUrl.href);
const assetRevision = globalThis.PANDOLAB_BUILD_META?.assetRevision || '';
const rasterContractUrl = new URL('./polygon-raster-contract.js', self.location.href);
const meshCoreUrl = new URL('./gpu-mesh-core.js', self.location.href);
const rpcHostUrl = new URL('./worker-rpc-host.js', self.location.href);
if (assetRevision) {
  rasterContractUrl.searchParams.set('v', assetRevision);
  meshCoreUrl.searchParams.set('v', assetRevision);
  rpcHostUrl.searchParams.set('v', assetRevision);
}
importScripts('./geographic-boundary-core.js', rasterContractUrl.href, meshCoreUrl.href, rpcHostUrl.href);

const meshCoreReady = import("../../document/temporal.js")
  .then(({ sharedCalculationCore }) => {
    self.PandoLabGpuMeshCore.setSharedCore(sharedCalculationCore);
    return sharedCalculationCore;
  });
meshCoreReady.catch(() => {}); // Each mesh operation awaits this prerequisite.
// The polygon asset catalog is not needed by a line-only overlay job.
let polygonPreparation = null;
let countryBoundaryState=null;
let boundarySeedPromise;
let boundarySeedFailure=null,boundarySeeded=false,boundaryChangedCount=0;
async function boundarySeed(){
 return boundarySeedPromise ||=Promise.all([import('../country-boundary-seed.js'),import('../../data/stored-asset-loader.js'),import('../../runtime/worker-asset-url.js')]).then(async([{loadCountryBoundarySeed},{createStoredAssetLoader},{workerBuildMeta,runtimeDataAssetUrl}])=>{
  const meta=workerBuildMeta(self.location.href,globalThis.PANDOLAB_BUILD_META);
  const store=createStoredAssetLoader({dataRevision:meta.dataRevision,cachePolicy:'immutable',resolveUrl:spec=>runtimeDataAssetUrl(self.location.href,spec)});
  return loadCountryBoundarySeed(meta,async spec=>(await store.loadAsset(spec,'background','country-boundary-seed','Country boundary seed',bytes=>JSON.parse(new TextDecoder().decode(bytes)))).value);
 }).catch(error=>{boundarySeedFailure=error?.message||String(error);return null;});
}
const preparedPolygonStore = () => polygonPreparation ||= meshCoreReady.then(() => Promise.all([
  import(`../prepared-polygon-mesh.js?v=${encodeURIComponent(assetRevision)}`),
  import(`../../data/stored-asset-loader.js?v=${encodeURIComponent(assetRevision)}`),
  import(`../../runtime/worker-asset-url.js?v=${encodeURIComponent(assetRevision)}`),
  import(`../../data/map-project-runtime.js?v=${encodeURIComponent(assetRevision)}`),
  import(`../../data/prepared-mesh-publication.js?v=${encodeURIComponent(assetRevision)}`),
])).then(async ([{ createPreparedPolygonMeshStore }, { createStoredAssetLoader },
  { runtimeDataAssetUrl, workerBuildMeta },{mapProjectCatalogSpec},{publishedPreparedMeshManifest}]) => {
  const engine = self.PandoLabGpuMeshCore;
  const meta = workerBuildMeta(self.location.href, globalThis.PANDOLAB_BUILD_META);
  const spec=mapProjectCatalogSpec(meta,'preparedMeshes');
  const catalogDirectory=spec.url.slice(0,spec.url.lastIndexOf('/')+1);
  const { loadAsset } = createStoredAssetLoader({ dataRevision: meta.dataRevision,
    cachePolicy: 'immutable', resolveUrl: asset => {
      // The selected project owns the mesh catalog directory; no default-world
      // version/path may be used as a fallback when the project changes.
      if (!asset.url.startsWith(catalogDirectory)||asset.url.includes('..'))
        throw new Error('Invalid project prepared polygon asset path');
      return runtimeDataAssetUrl(self.location.href, asset);
    } });
  const currentMesh=meta.projectCatalogs?.preparedMeshes?.current!==false;
  return createPreparedPolygonMeshStore({ engine,
    loadManifest: meta.resourceProfile === 'test-fixture'||!currentMesh ? null : async () => {
      const result = await loadAsset(spec, 'mesh', 'polygon-manifest', 'Prepared polygon manifest',
        buffer => JSON.parse(new TextDecoder().decode(buffer)));
      const manifest=result.value;
      if (manifest.schema !== 'pandolab-prepared-polygon-meshes'||manifest.schemaVersion!==2
        ||manifest.meshFormatVersion!==2||!/^[a-f0-9]{64}$/.test(manifest.algorithmSourceSha256||''))
        throw new Error('Invalid or unverifiable selected project prepared polygon manifest');
      // A different project's territory or physical land can never reuse its
      // old accelerators, even if the manifest itself has a valid SHA-256.
      for(const role of ['territorial','physicalLand']){
        const selected=meta.mapProject.resources[role].catalog;
        if(manifest.inputHashes?.[selected]!==meta.projectCatalogs[role].sha256)return null;
      }
      // Pinned data may have been generated by an earlier geometry algorithm.
      // Never decode those packets as current; recompute with the admitted
      // C++/WASM engine instead, keeping source-byte integrity checks intact.
      if (manifest.algorithmVersion !== engine.MESH_ALGORITHM_REVISION
        || manifest.maxEdgeDegrees !== engine.MAX_RENDER_EDGE_DEGREES) return null;
      return publishedPreparedMeshManifest(manifest);
    },
    loadAsset: async asset => (await loadAsset(asset, 'mesh', asset.sha256, 'Prepared polygon mesh', buffer => buffer)).value,
  });
});
let physicalDisplay=null;

self.PandoLabWorkerRpc.install({
  handlers: {
    'geometry.physical-land':async(payload,context)=>{
      context.throwIfCancelled();
      if(typeof payload.sourceKey!=='string'||!payload.sourceKey)throw new TypeError('Physical display needs its effective source identity.');
      if(physicalDisplay?.key===payload.sourceKey)return physicalDisplay.result;
      const [{dissolvePhysicalLand},core]=await Promise.all([import('../physical-land-display.js'),meshCoreReady]);
      const started=performance.now();
      const geometry=await dissolvePhysicalLand(payload.geometry,{
        union:coordinates=>core.polygonOperation('union',[coordinates],false),
        checkpoint:async()=>{context.throwIfCancelled();await new Promise(resolve=>setTimeout(resolve,0));context.throwIfCancelled();},
      });
      context.throwIfCancelled();
      const result={geometry,durationMs:performance.now()-started};
      physicalDisplay={key:payload.sourceKey,result};return result;
    },
    'geometry.prepare': async (payload, context) => {
      // A line-only overlay does not require the polygon prepared-mesh store,
      // immutable polygon catalogs or their initialization before it can draw.
      const requiresPolygons = payload.items.some(item => item.kind !== 'stroke');
      const store = requiresPolygons ? await preparedPolygonStore() : null;
      const packets = new Array(payload.items.length), packetTimings=[];
      const total = payload.items.length + 1;
      const progress = (completed, phase) => context.emitEvent('geometry.prepare-progress',
        { requestId: context.requestId, completed, total, phase }, { projectRevision: context.projectRevision });
      progress(1, 'initialized');
      // Two independent immutable asset reads may overlap without growing
      // the mobile decode/triangulation working set beyond two packets.
      for(let index=0;index<payload.items.length;index+=2){
        const batch=payload.items.slice(index,index+2);
        const rows=await Promise.all(batch.map(async sourceItem=>{let item=sourceItem;
          context.throwIfCancelled();
          const started=performance.now(),before=store?.stats?.()||null;
          let prepared;
          if(item.kind==='stroke'){
            if(item.countryFeatures){
              await meshCoreReady;
              const {createCountrySharedBoundaryState,visibleCountrySharedSegments}=await import('../country-shared-boundary-packet.js');
              if(!Array.isArray(item.countryVisibleIds))throw new TypeError('Shared country strokes require visible owner IDs.');
              const {countryBoundaryOwner,countryBoundarySeedOptions}=await import('../country-boundary-seed.js');
              const features=item.countryFeatures.map(feature=>({...feature,id:countryBoundaryOwner(feature.id)}));
              const options=countryBoundarySeedOptions(features,await boundarySeed());boundarySeeded=!!options;boundaryChangedCount=options?.changedIds.size??features.length;
              let segments;
              if(options&&!options.changedIds.size)segments=options.cachedSegments;
              else{if(!countryBoundaryState){countryBoundaryState=createCountrySharedBoundaryState();countryBoundaryState.replace(features,options);}else countryBoundaryState.replace(features);segments=countryBoundaryState.segments();}
              const visibleIds=new Set(item.countryVisibleIds.map(countryBoundaryOwner));
              item={...item,geometry:{type:'MultiLineString',coordinates:visibleCountrySharedSegments(segments,id=>visibleIds.has(id)).map(segment=>[segment.start,segment.end])}};
            }
            if(!['LineString','MultiLineString'].includes(item.geometry?.type))
              throw new TypeError('Only line strokes may use the geographic stroke Worker path');
            const {geographicStrokeChains}=await import('../maplibre-vector-group.js');
            const values=[];for(const line of item.geometry.type==='LineString'?[item.geometry.coordinates]:item.geometry.coordinates)for(let i=1;i<line.length;i++)values.push(...line[i-1],...line[i]);
            prepared={cacheKey:item.cacheKey,geometry:geographicStrokeChains(values)};
          }else prepared=await store.prepare(item,context);
          const after=store?.stats?.()||null;
          return {prepared,timing:{key:String(item.cacheKey),kind:item.kind,
            durationMs:performance.now()-started,
            packetBytes:Object.values(prepared.packet||{}).reduce((n,value)=>n+(ArrayBuffer.isView(value)?value.byteLength:0),0),
            assetHitsBefore:before?.assetHits??null,assetHitsAfter:after?.assetHits??null}};
        }));
        context.throwIfCancelled();
        for(let j=0;j<rows.length;j++){
          packets[index+j]=rows[j].prepared;packetTimings.push(rows[j].timing);
          progress(index+j+2,batch[j].kind==='stroke'?'stroke':'polygon');
        }
      }
      const buffers = [...new Set(packets.flatMap(({ packet }) => Object.values(packet||{})
        .filter(ArrayBuffer.isView).map(value => value.buffer)))];
        return self.PandoLabWorkerRpc.transferResult({packets,stats:{...(store?.stats()||{}),boundarySeedFailure,boundarySeeded,boundaryChangedCount,
        slowestPackets:packetTimings.sort((a,b)=>b.durationMs-a.durationMs).slice(0,8)}},buffers);
    },
  },
});
